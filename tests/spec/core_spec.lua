local Wow = require("tests.wow")

describe("core", function()
	it("loads from the TOC and logs in without errors", function()
		local wow = Wow.new():login()
		wow:assertNoErrors()
		assert.equals(1, wow.env.ScryDB.schemaVersion)
		assert.equals("0.1.0", wow.env.ScryDB.meta.addonVersion)
		assert.equals(16001, wow.env.ScryDB.meta.interface)
	end)

	it("keeps data across a reload", function()
		local wow = Wow.new():login()
		wow.env.ScryDB.characters["Other-Realm"] = { character = { name = "Other" } }
		wow:reload()
		wow:assertNoErrors()
		assert.equals("Other", wow.env.ScryDB.characters["Other-Realm"].character.name)
		assert.is_table(wow.env.ScryDB.characters["Tester-ArgentDawn"])
	end)

	it("resets a database written by a newer schema version", function()
		local wow = Wow.new({ saved = 'ScryDB = { schemaVersion = 999, future = "stuff" }' }):login()
		wow:assertNoErrors()
		assert.equals(1, wow.env.ScryDB.schemaVersion)
		assert.is_nil(wow.env.ScryDB.future)
	end)

	it("records handler errors in the dev log and still reports them to the game", function()
		local wow = Wow.new():login()
		wow.ns:On("PLAYER_LEVEL_UP", function()
			error("boom")
		end)
		wow:fire("PLAYER_LEVEL_UP", 81)
		wow:fire("PLAYER_LEVEL_UP", 82)
		assert.equals(2, #wow.errors)
		local errors = wow.env.ScryDevDB.errors
		assert.equals(1, #errors)
		assert.equals(2, errors[1].count)
		assert.matches("boom", errors[1].msg)
	end)

	it("describes exactly one session in ScryDevDB", function()
		local wow = Wow.new():login()
		wow.ns.Log:Info("from first session")
		wow:reload()
		for _, entry in ipairs(wow.env.ScryDevDB.log) do
			assert.not_equals("from first session", entry.msg)
		end
		assert.equals("source", wow.env.ScryDevDB.session.build)
	end)
end)

describe("dev builds", function()
	it("run the selftests shortly after login", function()
		local wow = Wow.new({ dev = true }):login()
		assert.is_nil(wow.env.ScryDevDB.selftest)
		wow:advance(3)
		wow:assertNoErrors()
		local st = wow.env.ScryDevDB.selftest
		assert.equals(0, st.failed, require("tests.util").dump(st.results))
		assert.is_true(st.total >= 3)
		assert.equals("test-dev-build", wow.env.ScryDevDB.session.build)
	end)

	it("do not run selftests in release builds", function()
		local wow = Wow.new():login()
		wow:advance(10)
		assert.is_nil(wow.env.ScryDevDB.selftest)
	end)
end)

describe("slash commands", function()
	it("/scry status prints version and build", function()
		local wow = Wow.new():login()
		wow:slash("/scry status")
		wow:assertNoErrors()
		assert.matches("Scry 0.1.0 %(build source", wow.printed[#wow.printed])
	end)

	it("/scry dev on persists across reloads", function()
		local wow = Wow.new():login()
		wow:slash("/scry dev on")
		wow:reload()
		assert.is_true(wow.ns.Log:IsDev())
		wow:slash("/scry dev off")
		wow:reload()
		assert.is_false(wow.ns.Log:IsDev())
	end)

	it("/scry rl reloads and /scry shot takes a screenshot", function()
		local wow = Wow.new():login()
		wow:slash("/scry rl")
		wow:slash("/scry shot")
		assert.is_true(wow.reloadRequested)
		assert.equals(1, wow.screenshots)
	end)

	it("unknown input prints help", function()
		local wow = Wow.new():login()
		wow:slash("/scry nonsense")
		assert.matches("Scry commands", wow.printed[#wow.printed])
	end)
end)
